/** P4.6d: REAL local Comfy scoped cancel against two disposable tiny prompts.
 *
 * Explicit opt-in: node scripts/p46d-comfy-scoped-cancel-live.mjs --live-scoped-cancel
 * Refuses a non-loopback URL, a nonempty queue, missing nodes or unknown APIs.
 * Never calls /interrupt, /queue POST, /free, or touches a user Project/SQLite.
 * Uses an EmptyImage -> Sleep -> PreviewImage graph (64px, no model loaded).
 */
import {randomUUID} from "node:crypto";
import {mkdtempSync,writeFileSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {setTimeout as sleep} from "node:timers/promises";

if(process.argv.slice(2).join(" ")!=="--live-scoped-cancel")
 throw Error("p46d_requires_explicit_live_scoped_cancel_opt_in");
const origin=new URL(process.env.ATELIER_P46D_COMFY_URL??"http://127.0.0.1:8188");
if(origin.protocol!=="http:"||!["127.0.0.1","[::1]"].includes(origin.hostname)||
 !origin.port||origin.pathname!=="/"||origin.username||origin.password||origin.search||origin.hash)
 throw Error("p46d_refuses_non_loopback_target");
const reportDir=mkdtempSync(join(tmpdir(),"infinite-atelier-p46d-"));
const reportPath=join(reportDir,"scoped-cancel-report.json");
const report={protocol:"P4.6d",mode:"real_comfy_non_gpu_short_sleep",checks:[],
 submitted:0,scopedCancels:0,forbiddenGlobalInterruptCalls:0,phase:"started"};
const owned=new Set();
const source=origin.origin;
const assert=(condition,name)=>{if(!condition)throw Error("p46d_assertion_failed:"+name);
 report.checks.push(name);console.log("P46D_ASSERT "+name)};
const json=async(path,{method="GET",body}={})=>{
 if(!path.startsWith("/")||path.startsWith("//")||path.includes(".."))throw Error("p46d_invalid_path");
 // All POSTs are strictly enumerated here and must be generated by this script.
 if(method==="POST"&&!((path==="/prompt")||
  /^\/api\/jobs\/[0-9a-f-]{36}\/cancel$/.test(path)))
  throw Error("p46d_forbidden_post_path");
 const response=await fetch(source+path,{method,redirect:"manual",
  headers:body?{"Content-Type":"application/json"}:{},
  body:body?JSON.stringify(body):undefined,signal:AbortSignal.timeout(11000)});
 if(!response.ok)throw Error("p46d_http_"+response.status+"_"+path.split("?")[0]);
 return response.json();
};
const queue=()=>json("/queue");
const idIn=(group,id)=>Array.isArray(group)&&group.some(row=>Array.isArray(row)&&row[1]===id);
const status=async id=>{
 const q=await queue();return {
  running:idIn(q.queue_running,id),pending:idIn(q.queue_pending,id),
  others:[...(q.queue_running??[]),...(q.queue_pending??[])].map(row=>row?.[1]).filter(x=>x!==id)
 };
};
const until=async(check,name,maxMs=7000)=>{
 const start=Date.now();
 while(Date.now()-start<maxMs){
  const outcome=await check();
  if(outcome)return outcome;
  await sleep(120);
 }
 throw Error("p46d_timeout:"+name);
};
const graph=seconds=>({
 "1":{class_type:"EmptyImage",inputs:{width:64,height:64,batch_size:1,color:0}},
 "2":{class_type:"Sleep",inputs:{input:["1",0],minutes:0,seconds}},
 "3":{class_type:"PreviewImage",inputs:{images:["2",0]}}
});
const submit=async(seconds,tag)=>{
 const clientId="p46d-"+randomUUID(), marker="p46d-"+randomUUID();
 const response=await json("/prompt",{method:"POST",body:{
  client_id:clientId,prompt:graph(seconds),
  extra_data:{infinite_atelier_submit_marker:marker,
   p46d_explicit_scoped_cancel_acceptance:tag}}});
 if(typeof response.prompt_id!=="string"||!/^[0-9a-f-]{36}$/i.test(response.prompt_id))
  throw Error("p46d_prompt_response_unknown_must_reconcile_manually");
 owned.add(response.prompt_id);report.submitted++;
 return response.prompt_id;
};
const scopedCancel=async id=>{
 if(!owned.has(id))throw Error("p46d_refuses_cancel_foreign_job");
 report.scopedCancels++;
 return json("/api/jobs/"+id+"/cancel",{method:"POST"});
};
const capture=async id=>json("/history/"+id);
try{
 const initial=await queue();
 assert(Array.isArray(initial.queue_running)&&initial.queue_running.length===0&&
  Array.isArray(initial.queue_pending)&&initial.queue_pending.length===0,
  "exclusive_idle_queue_before_test");
 const [empty,sleeper,preview]=await Promise.all([
  json("/object_info/EmptyImage"),json("/object_info/Sleep"),json("/object_info/PreviewImage")]);
 assert(Boolean(empty.EmptyImage&&sleeper.Sleep&&preview.PreviewImage),"required_minimal_nodes_present");
 report.phase="active";
 const a=await submit(9,"running");
 await until(async()=>{const s=await status(a);return s.running&&!s.pending&&s.others.length===0},
  "first_owned_prompt_is_running");
 assert(true,"owned_first_prompt_in_running_queue");
 const b=await submit(2,"pending");
 await until(async()=>{
  const q=await queue();
  const ids=[...(q.queue_running??[]),...(q.queue_pending??[])].map(row=>row?.[1]);
  return idIn(q.queue_running,a)&&idIn(q.queue_pending,b)&&ids.length===2;
 },"second_owned_prompt_is_pending");
 assert(true,"owned_second_prompt_in_pending_queue");
 const bCancel=await scopedCancel(b);
 assert(bCancel?.cancelled===true,"scoped_pending_cancel_confirmed_true");
 const postB=await queue();
 assert(idIn(postB.queue_running,a),"pending_cancel_did_not_interrupt_unrelated_running_prompt");
 assert(!idIn(postB.queue_pending,b),"pending_cancel_dequeued_only_target");
 const aCancel=await scopedCancel(a);
 assert(aCancel?.cancelled===true,"scoped_running_cancel_confirmed_true");
 await until(async()=>{
  const q=await queue();
  return !idIn(q.queue_running,a)&&!idIn(q.queue_pending,a)&&
   !idIn(q.queue_running,b)&&!idIn(q.queue_pending,b)
 },"owned_running_prompt_reached_terminal",17000);
 assert(true,"both_owned_prompts_absent_from_live_queue");
 const ah=await capture(a),bh=await capture(b);
 const aEntry=ah?.[a]??null,bEntry=bh?.[b]??null;
 report.runningHistoryStatus=aEntry?.status?.status_str??null;
 report.runningHistoryCompleted=aEntry?.status?.completed??null;
 report.runningOutputsCount=aEntry?.outputs?Object.keys(aEntry.outputs).length:0;
 report.pendingHasHistory=!!bEntry;
 assert(!bEntry,"pending_prompt_never_executed");
 assert(aEntry?.status?.status_str!=="success"&&aEntry?.status?.completed!==true,
  "running_cancel_not_a_successful_preview");
 assert(!aEntry?.outputs||!Object.keys(aEntry.outputs).length,
  "running_cancel_no_downstream_output");
 const repeated=await scopedCancel(a);
 assert(repeated?.cancelled===false,"terminal_cancel_is_noop");
 assert(report.forbiddenGlobalInterruptCalls===0,"no_global_interrupt");
 report.phase="pass";
 console.log("P46D_REAL_SCOPED_CANCEL_PASS "+JSON.stringify({
  checks:report.checks.length,queuedCancel:true,runningCancel:true,
  runningHistoryStatus:report.runningHistoryStatus,submitted:report.submitted,
  globalInterrupts:0}));
}catch(error){
 report.phase="failed";report.error=String(error?.message??error);
 console.error("P46D_REAL_SCOPED_CANCEL_FAIL "+report.error);
 process.exitCode=1;
}finally{
 // Only cancel our own prompt IDs; do not touch foreign jobs or /interrupt.
 for(const id of owned){
  try{
   const s=await status(id);
   if(s.running||s.pending)await scopedCancel(id);
  }catch{/* leave the reason visible in the report, never use global interrupt */}
 }
 report.completedAt=new Date().toISOString();
 writeFileSync(reportPath,JSON.stringify(report,null,2));
 console.log("P46D_REPORT_PATH="+reportPath);
}
