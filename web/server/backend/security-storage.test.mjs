test("concurrent stale recovery has one winner and old release cannot remove the winner",async t=>{
 const dir=temp(t),lockPath=join(dir,"atelier-instance.lock");
 writeFileSync(lockPath,JSON.stringify({pid:99999999,token:"dead-owner",createdAt:1}));
 const modulePath=new URL("./instance-lock.mjs",import.meta.url).href;
 const script=`import {acquireInstanceLock} from ${JSON.stringify(modulePath)};
process.stdin.setEncoding("utf8");
process.stdout.write("ready\\n");
process.stdin.on("data",chunk=>{if(!chunk.includes("go"))return;try{const lock=acquireInstanceLock(process.argv[1]);process.stdout.write("acquired\\n");setTimeout(()=>{lock.release();process.exit(0)},1500)}catch(error){process.stdout.write("error:"+(error.code||"unknown")+"\\n");process.exit(2)}});`;
 const children=[0,1].map(()=>spawn(process.execPath,["--input-type=module","-e",script,dir],{stdio:["pipe","pipe","pipe"]}));
 t.after(()=>{for(const child of children)if(child.exitCode===null)child.kill()});
 const output=children.map(()=>"");
 const ready=children.map((child,index)=>new Promise((resolve,reject)=>{
  child.stdout.on("data",chunk=>{
   output[index]+=chunk.toString();
   if(output[index].includes("ready"))resolve();
  });
  child.once("error",reject);
 }));
 await Promise.all(ready);
 const exits=children.map(child=>new Promise(resolve=>child.once("exit",resolve)));
 for(const child of children)child.stdin.end("go\n");
 await Promise.all(exits);
 assert.equal(output.filter(value=>value.includes("acquired")).length,1);
 assert.equal(output.filter(value=>value.includes("error:instance_already_running")||value.includes("error:instance_lock_recovery_required")).length,1);
 const swapDir=join(dir,"release-race"),oldOwner=acquireInstanceLock(swapDir);
 unlinkSync(oldOwner.path);
 const newOwner=acquireInstanceLock(swapDir);
 oldOwner.release();
 assert.equal(hasInstanceLock(swapDir),true);
 newOwner.release();
});
test("BlobStore validates signatures, SHA-256, deduplicates, caps bytes, guards Range",async t=>{
 const dir=temp(t),db=new DatabaseSync(":memory:");t.after(()=>db.close());initializeSchema(db);
 const store=createBlobStore({dataDir:dir,db,maxBlobBytes:100});
 const png=Buffer.from([137,80,78,71,13,10,26,10,0,0,0,0,73,72,68,82]);
 const digest=sha(png);
 const first=await store.put([png],{mime:"image/png",expectedSha256:digest});
 assert.equal(first.blobId,digest);assert.equal(first.existing,false);
 const second=await store.put([png],{mime:"image/png"});
 assert.equal(second.existing,true);
 const storedPath=join(dir,"blobs",digest.slice(0,2),digest);
 writeFileSync(storedPath,Buffer.alloc(png.length,0x30));
 await assert.rejects(store.put([png],{mime:"image/png"}),/blob_integrity_error/);
 writeFileSync(storedPath,png);
 assert.equal(db.prepare("SELECT COUNT(*) AS n FROM blobs").get().n,1);
 assert.equal((await store.stat(digest)).byteSize,png.length);
 assert.deepEqual(store.parseRange("bytes=3-7",png.length),{start:3,end:7});
 assert.deepEqual(store.parseRange("bytes=-4",png.length),{start:12,end:15});
 assert.throws(()=>store.parseRange("bytes=99-100",png.length),/invalid_blob_range/);
 await assert.rejects(store.stat("../etc/passwd"),/blob_not_found/);
 await assert.rejects(store.put([Buffer.from("fake")],{mime:"image/png"}),/blob_mime_mismatch/);
 await assert.rejects(store.put([png],{mime:"image/png",expectedSha256:"0".repeat(64)}),/blob_digest_mismatch/);
 await assert.rejects(store.put([Buffer.alloc(101)],{mime:"text/plain"}),/blob_quota_exceeded/);
 await assert.rejects(store.put([Buffer.from([0x61,0xc3,0x28])],{mime:"text/plain"}),/blob_mime_mismatch/);
 const utf8=Buffer.from("你好","utf8");
 const textResult=await store.put([utf8.subarray(0,1),utf8.subarray(1,3),utf8.subarray(3)],{mime:"text/plain"});
 assert.equal(textResult.byteSize,utf8.length);
 const empty=await store.put([Buffer.alloc(0)],{mime:"text/plain"});
 assert.equal(empty.byteSize,0);
 assert.equal((await store.stat(empty.blobId)).byteSize,0);
 const mkv=Buffer.concat([Buffer.from([26,69,223,163]),Buffer.from("matroska")]);
 const video=await store.put([mkv],{mime:"video/x-matroska"});
 assert.equal(video.mimeType,"video/x-matroska");
 const emptyChunks=[];
 for await(const chunk of store.getStream(await store.stat(empty.blobId)))emptyChunks.push(chunk);
 assert.equal(Buffer.concat(emptyChunks).length,0);
 assert.deepEqual(readdirSync(join(dir,"tmp")),[]);
});
